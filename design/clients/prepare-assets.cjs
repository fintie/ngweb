// Proportionally resize original portfolio artwork; never redraw the company marks.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const sharp = require(path.join(root, 'site/node_modules/sharp'));
const assets = JSON.parse(fs.readFileSync(path.join(__dirname, 'assets.json'), 'utf8').replace(/^\uFEFF/, ''));
// Use the user's requested central estimates, with the basis kept out of public copy.
const research = JSON.parse(fs.readFileSync(path.join(__dirname, 'estimates.json'), 'utf8'));
const order = research.companies.slice().sort((a, b) => b.centralValueAud - a.centralValueAud).map(item => item.id);
(async () => {
  const clients = [];
  for (const id of order) {
    const asset = assets.find(item => item.id === id);
    if (!asset) throw new Error(`Missing asset: ${id}`);
    const result = await sharp(path.join(__dirname, 'references', `${id}.png`))
      .resize({ width: 600, height: 280, fit: 'inside', withoutEnlargement: true })
      .webp({ lossless: true }).toFile(path.join(root, 'site/public/img/clients', `${id}.webp`));
    clients.push({ id, name: asset.name, width: result.width, height: result.height });
  }
  fs.writeFileSync(path.join(root, 'site/src/data/clients.js'), `// Generated by design/clients/prepare-assets.cjs from the source manifest.\nexport const clients = ${JSON.stringify(clients, null, 2)};\n`);
  console.log(`Prepared ${clients.length} company logos.`);
})();
